#!/usr/bin/env bash
# Regenerates instructions/<layer>/README.md, the index of each layer, from the frontmatter and headings of its files
# and the layer's row in docs/README.md. Agents reach a layer's rules through its index: Claude Code follows the @ imports
# in it, other agents read the paths.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

for dir in "$root"/instructions/*/; do
  layer="$(basename "$dir")"
  description="$(awk -F'|' -v key="\`instructions/$layer/\`" '$2 ~ key { gsub(/^ +| +$/, "", $3); print $3 }' "$root/docs/README.md")"
  if [[ -z "$description" ]]; then
    echo "error: docs/README.md has no row for instructions/$layer/" >&2
    exit 1
  fi

  {
    echo "<!-- Synced from zencq/.github (instructions/$layer/). Generated by scripts/update-indexes.sh there; don't edit it by hand. -->"
    echo
    echo "# Layer \`$layer\`"
    echo
    echo "$description."
    echo
    echo "Read the files that apply to everything before any task, and the others when you work on the paths they apply to."
    echo
    echo "| File | Applies to | Topics |"
    echo "| --- | --- | --- |"
    for file in "$dir"*.instructions.md; do
      name="$(basename "$file")"
      apply_to="$(sed -n 's/^applyTo: *"\(.*\)"$/\1/p' "$file" | head -n 1)"
      if [[ "$apply_to" == "**" ]]; then
        apply_to="everything"
      else
        apply_to="\`${apply_to//,/\`, \`}\`"
      fi
      title="$(sed -n 's/^# //p' "$file" | head -n 1)"
      sections="$(sed -n 's/^## //p' "$file" | paste -sd ',' - | sed 's/,/, /g')"
      topics="$title"
      [[ -n "$sections" ]] && topics="$title: $sections"
      echo "| @$name | $apply_to | $topics |"
    done
  } > "$dir/README.md"
done
